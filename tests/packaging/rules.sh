#!/usr/bin/env bash
# Pattern: none (test). scripts/check_rust_rules.py (used by check.yml via actions/rust-rules): passes a clean tree, fails a rule break.
TR="$T/rules"; mkdir -p "$TR/src"
printf '//! Entry.\n//! Pattern: none\nfn main() {}\n' > "$TR/src/main.rs"
python3 -I "$ROOT/scripts/check_rust_rules.py" "$TR" >/dev/null && pass "rules: clean tree passes" || fail "rules: clean tree must pass"
echo 'fn main() {}' > "$TR/src/bad.rs"
python3 -I "$ROOT/scripts/check_rust_rules.py" "$TR" >/dev/null 2>&1 && fail "rules: missing module doc must fail" || pass "rules: missing module doc fails"
# Blinc in one place: a program (every repo but fs-components) has no blinc dependency and no blinc [patch].
rm -f "$TR/src/bad.rs"
printf '[package]\nname = "p"\n[dependencies]\nserde = "1"\n' > "$TR/Cargo.toml"
python3 -I "$ROOT/scripts/check_rust_rules.py" "$TR" >/dev/null && pass "rules: program without blinc passes" || fail "rules: program without blinc must pass"
printf '[package]\nname = "p"\n[dependencies]\nblinc_app = "0.6"\n' > "$TR/Cargo.toml"
python3 -I "$ROOT/scripts/check_rust_rules.py" "$TR" >/dev/null 2>&1 && fail "rules: blinc dependency must fail" || pass "rules: blinc dependency fails"
printf '[package]\nname = "p"\n[dependencies]\nx = { package = "blinc_layout", version = "0.6" }\n' > "$TR/Cargo.toml"
python3 -I "$ROOT/scripts/check_rust_rules.py" "$TR" >/dev/null 2>&1 && fail "rules: renamed blinc dependency must fail" || pass "rules: renamed blinc dependency fails"
printf '[package]\nname = "p"\n[patch.crates-io]\nblinc_app = { git = "https://github.com/FreeSynergy/Blinc", tag = "fs-blinc-1" }\n' > "$TR/Cargo.toml"
python3 -I "$ROOT/scripts/check_rust_rules.py" "$TR" >/dev/null 2>&1 && fail "rules: blinc patch must fail" || pass "rules: blinc patch fails"
mkdir -p "$TR/crates/fs-components"; : > "$TR/crates/fs-components/Cargo.toml"
python3 -I "$ROOT/scripts/check_rust_rules.py" "$TR" >/dev/null && pass "rules: fs-components may carry blinc" || fail "rules: fs-components may carry blinc"
rm -rf "$TR/crates" "$TR/Cargo.toml"
